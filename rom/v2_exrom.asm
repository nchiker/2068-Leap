; R9 production EXROM: retained platform services and V2 interactive shell.
    INCLUDE "include/hardware.inc"
    DEFINE V2_COMPACT_SYSVARS   ; R10.7 P5: drop V1-only sysvars (see include/sysvars.inc)
    INCLUDE "include/sysvars.inc"
    INCLUDE "include/v2_layout.inc"
    INCLUDE "build/v2_crossbank.inc"
    INCLUDE "include/keys.inc"
    INCLUDE "include/v2_ktab.inc"
    V2_KTAB_LIST
    DEVICE NOSLOT64K
    ORG V2_EXROM_ENTRY_ADDR
V2_EXROM_ENTRY:
    jp V2_COMMAND_LOOP

    ORG V2_EXROM_SAVE_ADDR
V2_EXROM_SAVE:
    call V2_VERIFY_KTAB
    jp STORAGE_SAVE
    ORG V2_EXROM_LOAD_ADDR
V2_EXROM_LOAD:
    call V2_VERIFY_KTAB
    jp STORAGE_LOAD
    ORG V2_EXROM_CALCULATE_ADDR
V2_EXROM_CALCULATE:
    call V2_VERIFY_KTAB
    jp CALC_EXROM_ENTRY
    ORG V2_EXROM_INT_TO_FP_ADDR
V2_EXROM_INT_TO_FP:
    call V2_VERIFY_KTAB
    jp CALC_INT_TO_FP
    ORG V2_EXROM_FP_TO_INT_ADDR
V2_EXROM_FP_TO_INT:
    call V2_VERIFY_KTAB
    jp CALC_FP_TO_INT
    ORG V2_EXROM_PUSH_PI_ADDR
V2_EXROM_PUSH_PI:
    call V2_VERIFY_KTAB
    jp CALC_PUSH_PI
    ORG V2_EXROM_PUSH_FP_RAW_ADDR
V2_EXROM_PUSH_FP_RAW:
    call V2_VERIFY_KTAB
    jp CALC_PUSH_FP_RAW
    ORG V2_EXROM_SOUND_ADDR
V2_EXROM_SOUND:
    call V2_VERIFY_KTAB
    jp SOUND_EXROM
    ORG V2_EXROM_EDITOR_INIT_ADDR
V2_EXROM_EDITOR_INIT:
    call V2_VERIFY_KTAB
    jp EDITOR_INIT
    ORG V2_EXROM_EDITOR_ENTER_ADDR
V2_EXROM_EDITOR_ENTER:
    call V2_VERIFY_KTAB
    jp EDITOR_ENTER
    ORG V2_EXROM_EDITOR_WRAP_CALC_ADDR
V2_EXROM_EDITOR_WRAP_CALC:
    call V2_VERIFY_KTAB
    jp EDITOR_WRAP_CALC
    ORG V2_EXROM_EDITOR_WRAP_OFFSET_ADDR
V2_EXROM_EDITOR_WRAP_OFFSET:
    call V2_VERIFY_KTAB
    jp EDITOR_WRAP_OFFSET_TO_ROWCOL
    ORG V2_EXROM_EDITOR_WRAP_ROWCOL_ADDR
V2_EXROM_EDITOR_WRAP_ROWCOL:
    call V2_VERIFY_KTAB
    jp EDITOR_WRAP_ROWCOL_TO_OFFSET
    ORG V2_EXROM_EDITOR_BLOCK_DELETE_ADDR
V2_EXROM_EDITOR_BLOCK_DELETE:
    call V2_VERIFY_KTAB
    jp EDITOR_BLOCK_DELETE
    ORG V2_EXROM_NUM_TO_STRING_ADDR
V2_EXROM_NUM_TO_STRING:
    call V2_VERIFY_KTAB
    jp BASIC_NUM_TO_STRING_EXROM
    ORG V2_EXROM_FLOAT_TO_STRING_ADDR
V2_EXROM_FLOAT_TO_STRING:
    call V2_VERIFY_KTAB
    jp BASIC_FLOAT_TO_STRING_EXROM
    ORG V2_EXROM_SP_TO_PTR_ADDR
V2_EXROM_SP_TO_PTR:
    call V2_VERIFY_KTAB
    jp CALC_SP_TO_NEXT_FREE_PTR
    ORG $C0D8
V2_VERIFY_KTAB:
    ld a, (V2_KTAB_MAGIC_ADDR)
    cp V2_KTAB_MAGIC
    ret z
.mismatch:
    jr .mismatch

    ORG V2_EXROM_CLEAR_ADDR
V2_EXROM_CLEAR:
    call V2_VERIFY_KTAB
    jp MEM_CLEAR_V2

    INCLUDE "kernel/storage/storage.asm"
    IFDEF STORAGE_TEST_FAKE_RECEIVE
        INCLUDE "rom/exrom_storage_test.asm"
    ELSE
        IFDEF STORAGE_TEST_FAKE_SEND
            INCLUDE "rom/exrom_storage_test.asm"
        ENDIF
    ENDIF
    INCLUDE "rom/exrom_format.asm"
    INCLUDE "rom/exrom_calc.asm"
    INCLUDE "rom/exrom_sound.asm"
    INCLUDE "rom/exrom_editor.asm"
    INCLUDE "rom/exrom_v2_shell.asm"
    DS V2_EXROM_IMAGE_END - $, $FF
    SAVEBIN "v2_exrom.bin", V2_EXROM_ENTRY_ADDR, V2_EXROM_IMAGE_SIZE
